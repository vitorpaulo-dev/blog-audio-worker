export function podcastScriptPrompt(input: {
  title: string;
  content: string;
  language: string;
}): string {
  const languageInstruction =
    input.language === "PORTUGUESE"
      ? [
          "Write every spoken line in natural Brazilian Portuguese.",
          "Use contemporary Brazilian Portuguese as spoken by software developers.",
          "Use common technical terms naturally in English when Brazilian developers normally use them that way.",
          "Do not translate technical terminology literally when that would sound unnatural to a Brazilian developer.",
          "Avoid excessively formal Brazilian Portuguese.",
        ].join("\n")
      : [
          "Write every spoken line in natural contemporary English.",
          "Use vocabulary that experienced software developers would naturally use in conversation.",
          "Avoid academic or unnecessarily formal English.",
        ].join("\n");

  const system = [
    HUMANIZER_RULES,
    "You produce podcast scripts for a software development blog.",
    languageInstruction,
  ].join("\n");

  const task = [
    "Create a two-speaker podcast episode discussing the blog post below.",
    "",
    "The HOST must speak the exact post title as the very first spoken text of the episode.",
    "The first turn must therefore have speaker HOST and its text must be exactly equal to the supplied post title.",
    "There must be nothing spoken before the title.",
    "",
    "Build the episode as a natural conversation rather than a section-by-section summary.",
    "Start from the article's actual subject and let the discussion naturally develop through its important ideas.",
    "Cover at least 90% of the article's meaningful concepts and information.",
    "Coverage must be conceptual: preserve the important meaning and technical substance without trying to reproduce the article's wording.",
    "",
    "The HOST should actively drive the discussion.",
    "The HOST can introduce topics, make technically correct observations, ask useful questions and connect concepts.",
    "The GUEST should provide useful technical explanation, context and nuance when appropriate.",
    "Do not create fake disagreement between the HOST and GUEST.",
    "Do not have the GUEST correct or contradict the HOST.",
    "",
    "The speakers may react naturally to one another.",
    "A turn may be short or long depending on what sounds natural.",
    "Do not force a rigid alternation pattern, but keep both speakers meaningfully involved.",
    "Avoid having one speaker dominate the majority of the episode without a conversational reason.",
    "Split long explanations into multiple turns when doing so improves the natural flow.",
    "Prefer keeping individual turns below roughly 400 words.",
    "There is no maximum episode length. Generate as many turns as necessary to achieve natural flow and at least 90% conceptual coverage.",
    "",
    "The podcast should be technical enough for software developers, but it should not become a deep-dive tutorial.",
    "Explain the important idea and why it matters before going unnecessarily deep into implementation detail.",
    "Prioritize architecture, reasoning, trade-offs, important implementation choices and practical implications.",
    "",
    "The article may contain code, configuration, diagrams represented as text, commands or technical examples.",
    "Discuss those elements by explaining their purpose and behavior in spoken language.",
    "Do not read code line by line.",
    "Mention identifiers such as class names, methods, APIs or configuration keys only when useful.",
    "",
    "You may add concise relevant context that is not explicitly stated in the article.",
    "Only add context that is broadly established or strongly supported by the technical context.",
    "Never invent project history, measurements, implementation details, testing results, experiences or claims.",
    "",
    "The article is provided as raw markdown.",
    "Interpret the markdown structure as source material, but never read markdown syntax aloud.",
    "",
    "The podcast must not contain a generic introduction, generic outro, sponsorship, call to action, narration, stage direction or unrelated tangent.",
    "Begin immediately with the exact title and finish naturally once the meaningful discussion is complete.",
    "",
    "Respond with ONLY a valid JSON array.",
    "Every array item must be an object with exactly two properties: speaker and text.",
    'speaker must be either "HOST" or "GUEST".',
    "text must contain only the spoken prose for that turn.",
    "Do not add any properties.",
    "Do not wrap the JSON in markdown fences.",
    "Do not prepend or append explanatory prose outside the JSON array.",
    "Ensure the JSON is syntactically valid and properly escapes quotation marks, backslashes and line breaks inside string values.",
    "",
    "POST TITLE:",
    input.title,
    "",
    "POST CONTENT (raw markdown):",
    input.content,
  ].join("\n");

  return `${system}\n\n${task}`;
}

